export function messageText(value: string, language: "vi" | "en"): string {
  if (language === "en") return value;
  if (vietnamese[value]) return vietnamese[value];
  if (
    value.startsWith("Gemini model '") &&
    value.endsWith(" is unavailable; update GEMINI_MODEL")
  )
    return "Model Gemini chưa khả dụng cho khóa API này. Hãy kiểm tra GEMINI_MODEL.";
  if (value.includes("; "))
    return value
      .split("; ")
      .map((part) => messageText(part, language))
      .join("; ");
  if (value.startsWith("Value error, "))
    return messageText(value.slice(13), language);
  if (value === "Field required") return "Vui lòng điền đủ thông tin bắt buộc.";
  if (value === "Extra inputs are not permitted")
    return "Yêu cầu chứa trường dữ liệu không được hỗ trợ.";
  if (value.startsWith("String should have at least"))
    return "Nội dung quá ngắn. Hãy kiểm tra lại thông tin đã nhập.";
  if (value.startsWith("String should have at most"))
    return "Nội dung vượt độ dài cho phép.";
  if (
    value.startsWith("Input should be") ||
    value.startsWith("value is not a valid email")
  )
    return "Dữ liệu không đúng định dạng hoặc nằm ngoài giới hạn cho phép.";
  return value;
}
